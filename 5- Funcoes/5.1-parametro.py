# Definindo a função a ser utilizada
def imprimir(frase):
    print(frase)

#Utilizando variáveis para ser mostrado pela função
frase = input("Digite uma frase para imprimir na tela: ")
imprimir(frase)

palavra = input("Digite uma palavra para exibir na tela: ")
imprimir(palavra)

imprimir("Tô sem ideias")

imprimir(4 * 10)